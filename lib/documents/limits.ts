/**
 * 资料包处理引擎 · 资源上限（Agent 02「内存红线」的唯一事实来源）。
 *
 * 为什么把限额集中在一个文件：
 * 生产机是 **2 vCPU / 4 GiB、可用内存约 1.5 GB** 的阿里云 ECS，且同时跑着
 * ULTRON 内容矩阵。任何一处「悄悄把文件整份读进内存」都可能把宿主项目一起拖垮。
 * 因此所有解析/解压路径的上限必须只在一个地方定义、只在一个地方改。
 *
 * 三条纪律：
 * 1. 上传阶段的文件大小上限来自环境变量（MAX_UPLOAD_BYTES），这里给的是**硬上限**，
 *    即使环境变量被配得很大，也不会突破。
 * 2. 所有「必须整体读入内存」的格式，都要有可复现的降级路径，并且**如实标注**降级，
 *    不允许静默把空文本当成解析成功。
 * 3. 所有数值都要能被测试直接引用，不允许在实现里散落魔法数字。
 */

const KIB = 1024;
const MIB = 1024 * KIB;

/* ------------------------------------------------------------------ */
/* 上传                                                                */
/* ------------------------------------------------------------------ */

/** 单个上传文件的默认上限：20 MB（Agent 02 指令要求）。 */
export const DEFAULT_MAX_UPLOAD_BYTES = 20 * MIB;

/**
 * 单个上传文件的硬上限。
 * 即使有人把 MAX_UPLOAD_BYTES 配成 1 GB，也会被压回这个值 —— 保护内存与磁盘。
 */
export const ABSOLUTE_MAX_UPLOAD_BYTES = 50 * MIB;

/** 一次请求只允许一个文件，避免 N 份文件同时占内存/带宽。 */
export const MAX_FILES_PER_REQUEST = 1;

/** multipart 表单里非文件字段的上限，防止用超长字段打内存。 */
export const MAX_FORM_FIELDS = 8;
export const MAX_FORM_FIELD_BYTES = 4 * KIB;

/* ------------------------------------------------------------------ */
/* 提取文本                                                            */
/* ------------------------------------------------------------------ */

/**
 * 单份文档最多保留的纯文本字符数（约等于 0.9 MB UTF-8 中文）。
 * 超出部分被截断，且必须落库 truncated = true，绝不假装完整。
 */
export const MAX_EXTRACTED_CHARS = 300_000;

/* ------------------------------------------------------------------ */
/* PDF                                                                 */
/* ------------------------------------------------------------------ */

/**
 * PDF 允许「整体读入内存」的上限。
 *
 * ⚠️ 这是本引擎唯一无法完全避开整份读取的格式：PDF 的交叉引用表在文件末尾，
 * 文本与字体对象分散在全文，任何流式实现都要先建立随机访问索引。pdf.js 需要
 * 一份完整的字节缓冲。
 *
 * 因此采用三条限制把峰值压住，而不是假装能做到流式：
 *   1. 只允许「文件大小 ≤ 本上限」的 PDF 走内存路径，超限直接降级并如实标注；
 *   2. 解析串行执行（见 ./queue.ts），同一时刻进程内只解析一份文档；
 *   3. 输出文本按 MAX_EXTRACTED_CHARS 截断，避免文本侧再放大。
 *
 * 峰值估算：文件字节 + pdf.js 内部结构 ≈ 2~3 倍文件大小，20 MB 文件约 60 MB，
 * 在串行前提下对 1.5 GB 可用内存是安全的。
 */
export const PDF_MAX_IN_MEMORY_BYTES = 20 * MIB;

/* ------------------------------------------------------------------ */
/* XLSX                                                                */
/* ------------------------------------------------------------------ */

/** 单个工作表最多读取的行数。 */
export const XLSX_MAX_ROWS_PER_SHEET = 5_000;
/** 所有工作表合计最多读取的行数。 */
export const XLSX_MAX_ROWS_TOTAL = 20_000;
/** 所有工作表合计最多读取的单元格数（防止超宽表把内存打爆）。 */
export const XLSX_MAX_CELLS_TOTAL = 200_000;
/** 共享字符串表最多缓存的字符数（`xl/sharedStrings.xml` 是唯一必须缓存的整表）。 */
export const XLSX_MAX_SHARED_STRING_CHARS = 4 * 1_000_000;
/** 单个工作表 XML 条目的解压上限，防止压缩炸弹。 */
export const XLSX_MAX_ENTRY_UNCOMPRESSED_BYTES = 64 * MIB;
/** 一行最多保留的列数（超宽表只看前若干列，避免一行撑爆内存）。 */
export const XLSX_MAX_COLUMNS_PER_ROW = 200;
/** 元数据部件（workbook.xml / rels / styles.xml）单份解压上限。 */
export const XLSX_MAX_META_PART_BYTES = 8 * MIB;

/* ------------------------------------------------------------------ */
/* ZIP                                                                 */
/* ------------------------------------------------------------------ */

/** 一个 zip 里最多接受多少条目。 */
export const ZIP_MAX_ENTRIES = 50;
/** 一个 zip 解压后的总上限。 */
export const ZIP_MAX_TOTAL_UNCOMPRESSED_BYTES = 100 * MIB;
/** zip 内单个条目解压后的上限。 */
export const ZIP_MAX_ENTRY_UNCOMPRESSED_BYTES = 20 * MIB;
/** 压缩比上限（解压后 / 压缩前）。超过即视为压缩炸弹，整包拒绝。 */
export const ZIP_MAX_COMPRESSION_RATIO = 200;
/** 不允许嵌套 zip —— 递归解压是压缩炸弹最常见的放大器。 */
export const ZIP_ALLOW_NESTED = false;

/* ------------------------------------------------------------------ */
/* 任务                                                                */
/* ------------------------------------------------------------------ */

/** 单个文档的解析超时。超时按 FAILED 处理，不无限占用串行队列。 */
export const PARSE_TIMEOUT_MS = 120_000;

/**
 * 任务僵死阈值与错误信息长度上限已移到 `lib/jobs/limits.ts` ——
 * 它们是进程级约定，文档解析与审核引擎必须用同一套值。
 * 这里 re-export 是为了保持既有 import 不变。
 */
export { MAX_ERROR_MESSAGE_CHARS, STALE_JOB_THRESHOLD_MS } from "@/lib/jobs/limits";
