/**
 * 审核引擎 · 资源上限。
 *
 * 与 `lib/documents/limits.ts` 同一理由：生产机可用内存约 1.5 GB，
 * 且审核引擎会在**同一进程内**一次性持有所有选中资料的正文。
 * 上限只能在一处定义，不能散落在实现里。
 *
 * ⚠️ 一个容易忽略的换算：JS 字符串是 UTF-16，1 个中文字符占 2 字节，
 * 而正则匹配的中间产物还会再放大若干倍。所以「1.2 M 字符」在内存里
 * 远不止 1.2 MB —— 这是把总字符数上限压到百万级的真正原因。
 */

/**
 * 一次审核最多纳入的文档数。
 * 再多也不会让结论更准：审核的对象是「一个供应商的一包资料」，
 * 30 份已经覆盖了典型资料包的全部内容。
 */
export const MAX_DOCUMENTS_PER_RUN = 30;

/**
 * 一次审核读入正文的总字符上限。
 * 超出时按文档顺序逐份截断，并把该份标记为 truncated —— 由规则如实报出覆盖度不足，
 * 绝不静默丢内容。
 */
export const MAX_TOTAL_REVIEW_CHARS = 1_200_000;

/** 单次审核的执行超时。超时按 FAILED 处理，不无限占用串行队列。 */
export const REVIEW_TIMEOUT_MS = 60_000;

/** 任务停留在 RUNNING 超过该时长视为僵死（进程重启），允许被重新触发。 */
export const REVIEW_STALE_THRESHOLD_MS = 5 * 60 * 1000;

/**
 * 单次审核最多落库的发现数。
 * 这是一道工程兜底，不是业务规则：上限本身会在报告里如实说明，
 * 不会出现「明明报了 900 条却只显示 500 条而用户不知道」的情况。
 */
export const MAX_REVIEW_FINDINGS = 500;

/** 审核任务名称的长度上限（与数据库 text 列配合，防止畸形输入）。 */
export const MAX_RUN_NAME_CHARS = 120;
