/**
 * 作业层的通用上限。
 *
 * 放在 jobs 域而不是某个具体作业里，因为它们**不属于任何一个作业**：
 * 「错误信息能有多长」「多久没动静算僵死」是进程级的约定，
 * 文档解析与审核引擎共用同一套值。定义两遍必然漂移 —— 一处改了另一处忘了，
 * 症状是「同类失败在两个页面显示的信息长度不一样」这种无从解释的现象。
 */

/**
 * 落库的错误信息长度上限。
 * 目的是不把整个异常堆栈塞进数据库行里（那会让日志与列表页都不可读）。
 */
export const MAX_ERROR_MESSAGE_CHARS = 500;

/**
 * 作业停留在 RUNNING 超过这个时长即视为「僵死」（进程重启、容器被杀等），
 * 允许被重新认领，避免任务永远卡在运行中。
 */
export const STALE_JOB_THRESHOLD_MS = 10 * 60 * 1000;
